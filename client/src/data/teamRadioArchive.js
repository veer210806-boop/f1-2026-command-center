// Helper: Get radio transmissions between teammates
export const getTeammateRadio = (d1, d2) => {
  const codes = [d1.toUpperCase(), d2.toUpperCase()];
  const matches = TEAM_RADIO_ARCHIVE.filter(r => codes.includes(r.driver_code));
  return matches;
};

// Helper: Get radio transmissions by circuit
export const getCircuitRadio = (circuitId) => {
  if (!circuitId) return TEAM_RADIO_ARCHIVE;
  const matches = TEAM_RADIO_ARCHIVE.filter(r => r.circuit_id === circuitId);
  return matches.length > 0 ? matches : TEAM_RADIO_ARCHIVE;
};

// Helper: Get radio transmissions by driver code
export const getDriverRadio = (driverCode) => {
  if (!driverCode) return TEAM_RADIO_ARCHIVE;
  const matches = TEAM_RADIO_ARCHIVE.filter(r => r.driver_code === driverCode.toUpperCase());
  return matches;
};

// Helper: Filter radio by category and search query
export const filterRadioArchive = ({ category = "ALL", driver = "ALL", query = "" }) => {
  return TEAM_RADIO_ARCHIVE.filter(r => {
    const matchCat = category === "ALL" || r.category === category;
    const matchDriver = driver === "ALL" || r.driver_code === driver || r.team === driver;
    const matchQuery = !query ||
      r.message.toLowerCase().includes(query.toLowerCase()) ||
      (r.driver_reply && r.driver_reply.toLowerCase().includes(query.toLowerCase())) ||
      r.driver_name.toLowerCase().includes(query.toLowerCase()) ||
      r.grand_prix.toLowerCase().includes(query.toLowerCase());
    return matchCat && matchDriver && matchQuery;
  });
};
