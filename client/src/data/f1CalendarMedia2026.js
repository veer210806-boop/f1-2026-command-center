// 2026 Sprint Weekend rounds (6 confirmed sprint events)
export const SPRINT_ROUNDS_2026 = [2, 6, 10, 19, 21, 23]; // China, Miami, Austria, Austin, Brazil, Qatar

export function isSprintWeekend(round) {
  return SPRINT_ROUNDS_2026.includes(Number(round));
}

export function getRaceCardImage(circuitId) {
  if (!circuitId) return RACE_CARD_IMAGES.australia;
  const key = String(circuitId).toLowerCase().replace(/[-\s]/g, "_");
  return RACE_CARD_IMAGES[key] || RACE_CARD_IMAGES[circuitId] || RACE_CARD_IMAGES.australia;
}

